/* Testi dell'app in italiano, inglese e spagnolo. La lingua segue quella del
   dispositivo (device.getInfo().language); se non è una di queste, inglese.
   {n} e {team} sono segnaposto riempiti da fill(). Testi brevi: lo schermo del
   bracciale è largo 212px. */

export const LANGS = ['it', 'en', 'es'];

export function pickLang(code) {
  const c = String(code || '').slice(0, 2).toLowerCase();
  return LANGS.indexOf(c) >= 0 ? c : 'en';
}

export function fill(text, values) {
  return text.replace(/\{(\w+)\}/g, (all, k) => (values[k] === undefined ? all : String(values[k])));
}

